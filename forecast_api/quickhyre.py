# Cell 7 - Feature Engineering
from pandas.tseries.holiday import USFederalHolidayCalendar as _USCal

def create_features(df, label_col='Total'):
    df = df.copy()
    df = df.sort_values('Date').reset_index(drop=True)

    # Calendar features
    df['week_of_year'] = df['Date'].dt.isocalendar().week.astype(int)
    df['month'] = df['Date'].dt.month
    df['quarter'] = df['Date'].dt.quarter
    df['year'] = df['Date'].dt.year

    # Day-of-week (0 = Monday … 6 = Sunday)
    df['day_of_week'] = df['Date'].dt.dayofweek

    # Holiday flag: 1 if any US federal holiday falls within the 7-day week
    # starting on the row's date, 0 otherwise
    _cal = _USCal()
    _holidays = _cal.holidays(
        start=df['Date'].min(),
        end=df['Date'].max() + pd.Timedelta(days=6)
    )
    df['is_holiday'] = df['Date'].apply(
        lambda d: int(
            any(_holidays.isin(pd.date_range(d, periods=7, freq='D')))
        )
    )

    # Lag features (in weekly data: 1 week, 7 weeks, 30 weeks back)
    df['lag_1'] = df[label_col].shift(1)
    df['lag_7'] = df[label_col].shift(7)
    df['lag_30'] = df[label_col].shift(30)

    # Rolling statistics (window in weeks)
    df['rolling_mean_4'] = df[label_col].shift(1).rolling(window=4).mean()
    df['rolling_mean_8'] = df[label_col].shift(1).rolling(window=8).mean()
    df['rolling_std_4'] = df[label_col].shift(1).rolling(window=4).std()

    # Drop rows where lags are NaN (first 30 rows per state)
    df = df.dropna().reset_index(drop=True)

    return df

