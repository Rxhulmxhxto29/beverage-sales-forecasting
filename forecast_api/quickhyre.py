from prophet import Prophet

def train_prophet(train_df, val_df):
    # Prophet requires columns named ds and y
    prophet_train = train_df[['Date', 'Total']].rename(columns={'Date': 'ds', 'Total': 'y'})

    model = Prophet(
        yearly_seasonality=True,
        weekly_seasonality=False,
        daily_seasonality=False,
        seasonality_mode='multiplicative'
    )
    model.fit(prophet_train)

    # Create future dataframe for val period
    future = pd.DataFrame({'ds': val_df['Date'].values})
    forecast = model.predict(future)['yhat'].values

    val_series = val_df['Total'].values
    mae = mean_absolute_error(val_series, forecast)
    rmse = np.sqrt(mean_squared_error(val_series, forecast))
    mape = np.mean(np.abs((val_series - forecast) / val_series)) * 100

    return model, forecast, {'MAE': mae, 'RMSE': rmse, 'MAPE': mape}

