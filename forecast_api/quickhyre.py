# Cell 12 - LSTM training and evaluation
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout
from tensorflow.keras.callbacks import EarlyStopping
from sklearn.preprocessing import MinMaxScaler

SEQUENCE_LENGTH = 12  # use last 12 weeks to predict next week

def create_sequences(data, seq_length):
    X, y = [], []
    for i in range(len(data) - seq_length):
        X.append(data[i:i+seq_length])
        y.append(data[i+seq_length])
    return np.array(X), np.array(y)

def train_lstm(train_df, val_df):
    train_values = train_df['Total'].values.reshape(-1, 1)
    val_values = val_df['Total'].values.reshape(-1, 1)

    scaler = MinMaxScaler()
    train_scaled = scaler.fit_transform(train_values)
    val_scaled = scaler.transform(val_values)

    # Combine for sequence creation, then split
    full_scaled = np.concatenate([train_scaled, val_scaled])
    X, y = create_sequences(full_scaled, SEQUENCE_LENGTH)

    X_train = X[:len(train_scaled) - SEQUENCE_LENGTH]
    y_train = y[:len(train_scaled) - SEQUENCE_LENGTH]
    X_val = X[len(train_scaled) - SEQUENCE_LENGTH:]
    y_val = y[len(train_scaled) - SEQUENCE_LENGTH:]

    model = Sequential([
        LSTM(64, input_shape=(SEQUENCE_LENGTH, 1), return_sequences=True),
        Dropout(0.2),
        LSTM(32),
        Dropout(0.2),
        Dense(1)
    ])
    model.compile(optimizer='adam', loss='mse')

    early_stop = EarlyStopping(patience=10, restore_best_weights=True)
    model.fit(X_train, y_train,
              epochs=100,
              batch_size=16,
              validation_data=(X_val, y_val),
              callbacks=[early_stop],
              verbose=0)

    forecast_scaled = model.predict(X_val, verbose=0)
    forecast = scaler.inverse_transform(forecast_scaled).flatten()
    y_val_actual = scaler.inverse_transform(y_val.reshape(-1, 1)).flatten()

    mae = mean_absolute_error(y_val_actual, forecast)
    rmse = np.sqrt(mean_squared_error(y_val_actual, forecast))
    mape = np.mean(np.abs((y_val_actual - forecast) / y_val_actual)) * 100

    return model, scaler, forecast, {'MAE': mae, 'RMSE': rmse, 'MAPE': mape}

