    history = full_df['Total'].tolist()
    last_date = full_df['Date'].iloc[-1]

    preds = []
    for i in range(n):
        next_date = last_date + pd.Timedelta(weeks=i+1)
        lag_1  = history[-1]
        lag_7  = history[-7] if len(history) >= 7 else history[0]
        lag_30 = history[-30] if len(history) >= 30 else history[0]
        roll4  = np.mean(history[-4:])
        roll8  = np.mean(history[-8:])
        std4   = np.std(history[-4:])

        features = np.array([[
            next_date.isocalendar()[1],
            next_date.month,
            next_date.quarter,
            next_date.year,
            lag_1, lag_7, lag_30,
            roll4, roll8, std4
        ]])
        features_scaled = scaler.transform(features)
        pred = model.predict(features_scaled)[0]
        preds.append((next_date.strftime('%Y-%m-%d'), round(float(pred), 2)))
        history.append(pred)

    return preds

