    model = load_model(model_path)
    scaler = joblib.load(scaler_path)

    full_df = featured_state_dfs[state]['full']
    last_date = full_df['Date'].iloc[-1]
    history = full_df['Total'].values.tolist()

    preds = []
    sequence = list(scaler.transform(np.array(history[-SEQUENCE_LENGTH:]).reshape(-1,1)).flatten())

    for i in range(n):
        next_date = last_date + pd.Timedelta(weeks=i+1)
        x = np.array(sequence[-SEQUENCE_LENGTH:]).reshape(1, SEQUENCE_LENGTH, 1)
        pred_scaled = model.predict(x, verbose=0)[0][0]
        pred = scaler.inverse_transform([[pred_scaled]])[0][0]
        preds.append((next_date.strftime('%Y-%m-%d'), round(float(pred), 2)))
        sequence.append(pred_scaled)

    return preds

