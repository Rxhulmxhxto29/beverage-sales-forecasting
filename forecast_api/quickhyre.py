# Cell 9 - ARIMA/SARIMA training and evaluation
from pmdarima import auto_arima
from sklearn.metrics import mean_absolute_error, mean_squared_error

def train_arima(train_series, val_series):
    model = auto_arima(
        train_series,
        seasonal=True,
        m=52,                  # weekly seasonality
        stepwise=True,
        suppress_warnings=True,
        error_action='ignore',
        max_p=3, max_q=3,
        max_P=1, max_Q=1,
        d=None,                # auto-detect differencing
        information_criterion='aic',
        n_jobs=-1
    )

    # Forecast val_size steps ahead
    forecast = model.predict(n_periods=len(val_series))

    mae = mean_absolute_error(val_series, forecast)
    rmse = np.sqrt(mean_squared_error(val_series, forecast))
    mape = np.mean(np.abs((val_series - forecast) / val_series)) * 100

    return model, forecast, {'MAE': mae, 'RMSE': rmse, 'MAPE': mape}

